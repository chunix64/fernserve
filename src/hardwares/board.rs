use esp_hal::clock::CpuClock;
use esp_hal::peripherals::FROM_CPU_INTR0;
use esp_hal::timer::timg::TimerGroup;

use crate::models::configs::AppPeripherals;

pub struct Board {
    pub app_peripherals: AppPeripherals,
}

impl Board {
    pub fn init() -> Self {
        let config = esp_hal::Config::default().with_cpu_clock(CpuClock::max());
        let peripherals = esp_hal::init(config);

        // Allocate ~160KB for heap
        esp_alloc::heap_allocator!(#[esp_hal::ram(reclaimed)] size: 98768); // Max size of the reclaimed memory from the bootloader
        esp_alloc::heap_allocator!(size: 64 * 1024); // 64 KB decrease if crashed because of running out of stack memory

        esp_println::logger::init_logger_from_env();
        Self::start_freertos(peripherals.TIMG0, peripherals.FROM_CPU_INTR0);

        // ------------- Generated by esp-generate for esp32 -------------
        // The following pins are used to bootstrap the chip. They are available
        // for use, but check the datasheet of the module for more information on them.
        // - GPIO0
        // - GPIO2
        // - GPIO5
        // - GPIO12
        // - GPIO15
        // These GPIO pins are in use by some feature of the module and should not be used.
        let _gpio6 = peripherals.GPIO6;
        let _gpio7 = peripherals.GPIO7;
        let _gpio8 = peripherals.GPIO8;
        let _gpio9 = peripherals.GPIO9;
        let _gpio10 = peripherals.GPIO10;
        let _gpio11 = peripherals.GPIO11;
        let _gpio16 = peripherals.GPIO16;
        let _gpio20 = peripherals.GPIO20;
        // ---------------------------------------------------------------

        let app_peripherals = AppPeripherals {
            wifi: peripherals.WIFI,
            flash: peripherals.FLASH,
        };

        Self { app_peripherals }
    }

    fn start_freertos(
        timer_group: impl esp_hal::timer::timg::TimerGroupInstance + 'static,
        sw_interupt: FROM_CPU_INTR0<'static>,
    ) {
        let timg0 = TimerGroup::new(timer_group);
        esp_rtos::start(timg0.timer0, sw_interupt);
    }
}
